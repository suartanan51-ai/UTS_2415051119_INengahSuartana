create table public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  course text not null,
  due_date timestamptz not null,
  priority text not null default 'Sedang',
  is_completed boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.tasks enable row level security;
create policy "demo read tasks" on public.tasks for select to anon using (true);
create policy "demo insert tasks" on public.tasks for insert to anon with check (true);
create policy "demo update tasks" on public.tasks for update to anon using (true) with check (true);
create policy "demo delete tasks" on public.tasks for delete to anon using (true);
